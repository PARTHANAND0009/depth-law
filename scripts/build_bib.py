#!/usr/bin/env python3
"""Build paper/refs.bib entries from official metadata (export.arxiv.org for arXiv ids, api.crossref.org for
DOIs), so titles, authors and years are copied, not typed. Keys and ids are listed below; scripts/verify_bib.py
then re-checks every title. Usage: build_bib.py > paper/refs.bib"""
import json, re, sys, time, urllib.request
import xml.etree.ElementTree as ET

