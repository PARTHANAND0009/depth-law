# H-R robustness variants (non-gating)
VAR = [("CorrectOnly", "correct rows only"), ("IncorrectOnly", "incorrect rows only"),
       ("CollapseExcl", "high-collapse relations excluded"), ("WholeWord", "whole-word objects"),
       ("FracQuarter", "threshold 0.25 of final p"), ("FracThreeQuarter", "threshold 0.75 of final p"),
       ("TemplateA", "template 0 only"), ("TemplateB", "template 1 only"), ("TemplateC", "template 2 only"),
       ("CarrierA", "carrier 0 only"), ("CarrierB", "carrier 1 only"), ("CarrierC", "carrier 2 only"),
       ("SecPZeroOne", "secondary: $p\\ge 0.1$ onset"), ("SecRankOne", "secondary: rank-1 onset")]
rows = []
for k, lab in VAR:
    cells = []
    for mod in ("PyOneFour", "PyTwoEight", "OlmoSeven"):
        cells += [m(f"hrIcc{k}{mod}"), m(f"hrDRsq{k}{mod}")]
    rows.append(f"{lab} & " + " & ".join(cells) + " \\\\")
rows.append("secondary: logit-diff onset & \\multicolumn{6}{c}{PENDING (GPU; not run)} \\\\")
write("hrvar.tex", [
    "\\begin{tabular}{@{}lrrrrrr@{}}", "\\toprule",
    " & \\multicolumn{2}{c}{\\PythiaOneFourB} & \\multicolumn{2}{c}{\\PythiaTwoEightB} & \\multicolumn{2}{c}{OLMo-2-7B} \\\\",
    "\\cmidrule(lr){2-3}\\cmidrule(lr){4-5}\\cmidrule(l){6-7}",
    "variant & $\\mathrm{ICC}_{rel}$ & \\DRsq & $\\mathrm{ICC}_{rel}$ & \\DRsq & $\\mathrm{ICC}_{rel}$ & \\DRsq \\\\",
    "\\midrule", *rows, "\\bottomrule", "\\end{tabular}"])

# gate reviews (verbatim files; verdict line only)
S = json.loads((ROOT / "results/integrity/summary.json").read_text())
esc = lambda s: s.replace("_", "\\_")
rows = [f"{esc(r['gate'])} & {esc(r['agent'])} & {esc(r['verdict'].split(' (')[0])} \\\\" for r in S["reviews"]]
write("reviews.tex", ["\\begin{tabular}{@{}lll@{}}", "\\toprule", "gate & reviewer agent & verdict \\\\", "\\midrule",
                      *rows, "\\bottomrule", "\\end{tabular}"])
# guard tests
