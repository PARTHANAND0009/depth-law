#!/usr/bin/env python3
"""Generate appendix tables for the paper (paper/generated/*.tex). Cells are numbers.tex macro NAMES, never digits,
so every value stays traceable to its results file; the reviews table is copied from results/integrity/summary.json
(gate, agent, verdict words). Refuses to write a macro that numbers.tex does not define. Run through log_run.py."""
import json, pathlib, re, sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
G = ROOT / "paper" / "generated"
DEFINED = set(re.findall(r"\\newcommand\{\\(\w+)\}", (ROOT / "paper/numbers.tex").read_text()))


def m(name):
    assert name in DEFINED, f"macro \\{name} not in numbers.tex"
    return "\\" + name


def write(fn, lines):
    G.mkdir(parents=True, exist_ok=True)
    (G / fn).write_text("% GENERATED by scripts/make_tables.py; do not edit.\n" + "\n".join(lines) + "\n")
    print("wrote", (G / fn).relative_to(ROOT))


# robustness simulation (non-selecting)
rows = []
for t in ("A", "B"):
    for l in ("TwentyFour", "ThirtySix"):
        for nc in ("Three", "Two"):
            k = f"ptRob{t}L{l}Nc{nc}"
            lab = f"{t}, $L$ {'24' if l == 'TwentyFour' else '36'}, $n_c$ {'3' if nc == 'Three' else '2'}"
            rows.append(f"{lab} & {m(k + 'N')} & {m(k + 'CovIcc')} & {m(k + 'BiasIcc')} & {m(k + 'CovDiff')} & "
                        f"{m(k + 'BiasDiff')} & {m(k + 'DiffLoPos')} \\\\")
write("robust.tex", [
    "\\begin{tabular}{@{}lrrrrrr@{}}", "\\toprule",
    "condition & $N$ & cov.\\ \\ICCone & bias & cov.\\ diff & bias & diff lo $>0$ \\\\", "\\midrule", *rows,
    "\\bottomrule", "\\end{tabular}"])

