"""Hardware probe and tier selection. Writes reports/hw.json and configs/tier.yaml."""
from __future__ import annotations

import json
import os
import platform
import shutil
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def _nvidia_smi() -> list[dict]:
    exe = shutil.which("nvidia-smi")
    if not exe:
        return []
    out = subprocess.run(
        [exe, "--query-gpu=name,memory.total,driver_version", "--format=csv,noheader,nounits"],
        capture_output=True, text=True, check=False,
    ).stdout
    gpus = []
    for line in out.strip().splitlines():
        name, mem, drv = [x.strip() for x in line.split(",")]
        gpus.append({"name": name, "mem_gb": round(int(mem) / 1024, 1), "driver": drv})
    return gpus


def _torch_info() -> dict:
    try:
        import torch
    except ImportError:
        return {"torch": None}
    info = {"torch": torch.__version__, "cuda_available": torch.cuda.is_available(),
            "cuda_version": torch.version.cuda}
    if torch.cuda.is_available():
        info["bf16"] = torch.cuda.is_bf16_supported()
        info["devices"] = [
            {"name": torch.cuda.get_device_name(i),
             "mem_gb": round(torch.cuda.get_device_properties(i).total_memory / 2**30, 1)}
            for i in range(torch.cuda.device_count())
        ]
    return info


def pick_tier(gpus: list[dict]) -> tuple[str, str]:
    if not gpus:
        return "CPU", "No CUDA GPU detected: only pythia-70m/410m tests, fact building and frequency counting (S0-S2)."
    mem = min(g["mem_gb"] for g in gpus)
    if mem >= 79:
        return "T2", f"{len(gpus)}x GPU, min {mem} GB >= 80 GB."
    if mem >= 24:
        return "T1", f"{len(gpus)}x GPU, min {mem} GB in [24, 80)."
    return "T0", f"{len(gpus)}x GPU, min {mem} GB < 24 GB."


def main() -> dict:
    gpus = _nvidia_smi()
    tinfo = _torch_info()
    if not gpus and tinfo.get("devices"):
        gpus = tinfo["devices"]
    du = shutil.disk_usage(ROOT)
    try:
        mem_gb = round(os.sysconf("SC_PAGE_SIZE") * os.sysconf("SC_PHYS_PAGES") / 2**30, 1)
    except (ValueError, OSError):
        mem_gb = None
    tier, why = pick_tier(gpus)
    report = {
        "utc": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "python": sys.version.split()[0], "platform": platform.platform(),
        "cpus": os.cpu_count(), "ram_gb": mem_gb,
        "disk_free_gb": round(du.free / 2**30, 1),
        "gpus": gpus, **tinfo, "tier": tier, "tier_reason": why,
    }
    (ROOT / "reports").mkdir(exist_ok=True)
    (ROOT / "reports" / "hw.json").write_text(json.dumps(report, indent=2) + "\n")
    (ROOT / "configs" / "tier.yaml").write_text(
        f"# generated by depthlaw.hw at {report['utc']}\ntier: {tier}\nreason: \"{why}\"\n"
        f"n_gpus: {len(gpus)}\n"
    )
    print(json.dumps(report, indent=2))
    return report


if __name__ == "__main__":
    main()
