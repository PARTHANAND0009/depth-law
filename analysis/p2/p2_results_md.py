"""Generate reports/p2/RESULTS.md from the P2 analysis outputs only (results/P2analysis/<set>/p2_results.json and
p2_decision.json), the GPU run dirs and the ledger. No number is typed by hand: every number below is read from those
files. Not frozen code (reporting only).
python analysis/p2/p2_results_md.py [out=reports/p2/RESULTS.md]"""
import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
A = ROOT / "results/P2analysis"
SETS = ["correct", "new226", "all", "all10", "nomanufacturer", "tcov", "lofo", "h4"]
ORDER = ["Qwen/Qwen3-8B", "meta-llama/Llama-3.1-8B", "EleutherAI/pythia-1.4b", "EleutherAI/pythia-2.8b", "allenai/OLMo-2-1124-7B"]


def f3(x):
    return "MISSING" if x is None else (f"{x:.3f}" if isinstance(x, float) else str(x))


def ci(c):
    return "MISSING" if not c or c[0] is None else f"[{c[0]:.3f}, {c[1]:.3f}]"


def nwarn(f):
    """Number of convergence warnings of one fit. R's toJSON(auto_unbox = TRUE) writes a single warning as a plain
    string and several as a list, so a string counts as 1 (not its length)."""
    w = f.get("warnings") if isinstance(f, dict) else None
    if not w:
        return 0
    return 1 if isinstance(w, str) else len(w)


def sha(p):
    return hashlib.sha256(Path(p).read_bytes()).hexdigest()[:16]


def ledger_runs():
    out = {}
    for l in open(ROOT / "results/ledger.jsonl"):
        e = json.loads(l)
        if e.get("kind") == "RUN" and str(e.get("tag", "")).startswith(("P2 analysis: set", "EXPLORATORY P2 analysis: set")):
            out[e["tag"].split("set ")[1].split(" ")[0]] = e
    return out


def main(out):
    L = []; w = L.append
    led = ledger_runs()
    R = {s: json.loads((A / s / "p2_results.json").read_text()) for s in SETS if (A / s / "p2_results.json").exists()}
    D = {s: json.loads((A / s / "p2_decision.json").read_text()) for s in SETS if (A / s / "p2_decision.json").exists()}
    rc, dc = R["correct"], D["correct"]
    w("# P2 results: prompt vs fact in causal resolution depth")
    w("")
    w("Preregistration: `prereg/P2_prompt_vs_fact.md` (tag prereg-P2 = ff119ca; sha256 in `prereg/HASH_P2.txt`). Deviations: "
      "`prereg/deviations/D-P2-20261124T044034Z-0.md` (off-instance copy mechanism; no measurement change). "
      "Generated by `analysis/p2/p2_results_md.py` from the files cited; every number is read from them. "
      "Only the `correct` set is gating; all other sets are preregistered sensitivities (not gating), and `h4` is EXPLORATORY.")
    w("")
    w("## 1. Provenance")
    w("| item | value |")
    w("|---|---|")
    w("| GPU session log | `results/logs/p2_gpu_run_20261124T162942Z.log` (RTX PRO 6000 Blackwell, fp32, git ff119ca) |")
    for spec in rc["runs"]:
        m, rd = spec.split("=", 1)
        w(f"| run dir {m} | `{rd}` (run_id `{Path(rd).name}`; manifest sha256 {sha(Path(ROOT, rd, 'manifest.json'))}…) |")
    for s in SETS:
        if s in led:
            e = led[s]
            w(f"| analysis call `{s}` | ledger RUN \"{e['tag']}\", utc_start {e['utc_start']}, exit {e.get('exit_code', e.get('exit'))}; "
              f"`results/P2analysis/{s}/p2_results.json` sha256 {sha(A / s / 'p2_results.json') if (A / s / 'p2_results.json').exists() else 'MISSING'}… |")
        else:
            w(f"| analysis call `{s}` | MISSING (no ledger RUN entry) |")
    w("")
    w(f"Carriers used (nc): {rc['n_carriers_used']}. Bootstrap: {rc['boot']} {rc['n_boot']} resamples. Seed: {rc['seed']}.")
    w("")
    w("## 2. Model inclusion (prereg sections 1 and 3)")
    w("| model | status | facts with ≥ 2 correct paraphrases | relations |")
    w("|---|---|---|---|")
    for m in ORDER:
        mm = rc["models"][m]; md = mm.get("min_data", {})
        w(f"| {m} | {mm['status']} | {md.get('facts_with_2plus_correct', 'MISSING')} | {md.get('relations_with_such_facts', 'MISSING')} |")
    w("")
    w("Rule: a model is included only if ≥ 150 of 300 facts have ≥ 2 correct paraphrases and they cover ≥ 15 of 20 relations.")
    w("")
    inc = [m for m in ORDER if rc["models"][m]["status"] == "ok"]
    w("## 3. Primary results (set `correct`; REML; parametric bootMer 95% percentile CIs; N rows / facts per model below)")
    w("| quantity | " + " | ".join(inc) + " |")
    w("|---|" + "---|" * len(inc))
    def row(label, fn):
        w(f"| {label} | " + " | ".join(fn(m) for m in inc) + " |")
    pm = dc["per_model"]
    row("rows (fact × paraphrase × carrier) / facts", lambda m: f"{rc['models'][m]['n_rows']} / {rc['models'][m]['n_facts']}")
    for y in ("D1", "D4"):
        row(f"ICC(1) {y} [CI]", lambda m, y=y: f"{f3(rc['models'][m]['fits'][y]['point']['icc1'])} {ci(rc['models'][m]['fits'][y]['boot']['ci']['icc1'])}")
        row(f"ICC(1) band {y}", lambda m, y=y: str(pm[m].get(f"icc1_band_{y}")))
        row(f"wording share {y} [CI]", lambda m, y=y: f"{f3(rc['models'][m]['fits'][y]['point']['wording'])} {ci(rc['models'][m]['fits'][y]['boot']['ci']['wording'])}")
        row(f"diff = wording − ICC(1) {y} [CI]", lambda m, y=y: f"{f3(rc['models'][m]['fits'][y]['point']['diff'])} {ci(rc['models'][m]['fits'][y]['boot']['ci']['diff'])}")
        row(f"MoM diff {y} (direction check)", lambda m, y=y: f3(rc['models'][m]['mom'][y].get('diff')))
    row("**H1** (wording > fact, D1 and D4, MoM agrees)", lambda m: f"**{pm[m]['H1']}**")
    row("**H1-alt** (ICC(1) ≥ 0.5, lower CI ≥ 0.4, D1 and D4, MoM diff < 0)", lambda m: f"**{pm[m]['H1_alt']}**")
    row("n′ for G = 0.8 (D1) [CI]", lambda m: f"{pm[m]['nprime_G_D1'] if pm[m]['nprime_G_D1'] is not None else 'undefined'} {ci(rc['models'][m]['fits']['D1']['boot']['ci']['nprime_G'])}")
    row("G ceiling fact/(fact + fc/nc) (D1)", lambda m: f3(pm[m]['G_ceiling_D1']))
    row("(rt + frame) − (ft + e/nc), share of den (D1) [CI]", lambda m: f"{f3(rc['models'][m]['fits']['D1']['point']['tf_minus_resid'])} {ci(rc['models'][m]['fits']['D1']['boot']['ci']['tf_minus_resid'])}")
    row("fact-share null p (D1; 1000 parametric datasets) / failed refits", lambda m: f"{f3(pm[m]['null_p_D1'])} / {rc['models'][m]['null'].get('n_failed')}")
    def h1_words(m):
        v = pm[m]
        if v['H1'] is None:
            return "MISSING"
        if v['H1']:
            return "H1 holds"
        return ("H1 not established: D1 diff CI lower bound " + f3(v['diff_D1_ci'][0]) + ", D4 diff CI lower bound "
                + f3(v['diff_D4_ci'][0]) + ", MoM diffs " + f3(v['mom_diff_D1']) + " / " + f3(v['mom_diff_D4'])
                + " (H1 needs all four conditions)")
    row("H1 status in words", h1_words)
    row("singular fit D1 / D4; warnings D1", lambda m: f"{rc['models'][m]['fits']['D1']['singular']} / {rc['models'][m]['fits']['D4']['singular']}; {nwarn(rc['models'][m]['fits']['D1'])}")
    row("failed bootstrap refits (icc1, D1 / D4)", lambda m: f"{rc['models'][m]['fits']['D1']['boot']['failed_frac']['icc1']} / {rc['models'][m]['fits']['D4']['boot']['failed_frac']['icc1']}")
    row("curves with p_final = 0 / < 1e-4 (all 300 × 10 × nc curves, before the inclusion set)", lambda m: f"{rc['models'][m]['n_curves_p_final_zero']} / {rc['models'][m]['n_curves_p_final_lt_1e-4']}")
    w("")
    w("Share of total variance (relation included), D1:")
    w("")
    w("| component | " + " | ".join(inc) + " |")
    w("|---|" + "---|" * len(inc))
    for k in ("fact", "relation", "frame", "rt", "ft", "fc", "residual"):
        w(f"| {k} | " + " | ".join(f3(rc['models'][m]['fits']['D1']['point']['share_total'][k]) for m in inc) + " |")
    w("")
    w("Secondary outcomes (D2, D3), set `correct`:")
    w("")
    w("| quantity | " + " | ".join(inc) + " |")
    w("|---|" + "---|" * len(inc))
    for y in ("D2", "D3"):
        row(f"ICC(1) {y} [CI]", lambda m, y=y: (f"{f3(rc['models'][m]['fits'][y]['point']['icc1'])} {ci(rc['models'][m]['fits'][y]['boot']['ci']['icc1'])}"
                                                if rc['models'][m]['fits'][y].get('status') == 'ok' else rc['models'][m]['fits'][y].get('status', 'MISSING')))
        row(f"diff {y} [CI]", lambda m, y=y: (f"{f3(rc['models'][m]['fits'][y]['point']['diff'])} {ci(rc['models'][m]['fits'][y]['boot']['ci']['diff'])}"
                                              if rc['models'][m]['fits'][y].get('status') == 'ok' else 'MISSING'))
        row(f"rows {y}", lambda m, y=y: str(rc['models'][m]['fits'][y].get('n_rows', 'MISSING')))
    w("")
    w("## 4. Claims (prereg sections 5–6; ≥ 2 families; computed in `results/P2analysis/correct/p2_decision.json`)")
    w(f"Families included: {dc['families']['included_families']}. H1 holds in families: {dc['families']['H1']}. "
      f"H1-alt holds in families: {dc['families']['H1_alt']}.")
    w("")
    w("| rule | result |")
    w("|---|---|")
    for k, v in dc["claims"].items():
        w(f"| {k} | {v} |")
    w("")
    w("## 5. H3 (estimation only): cross-model Spearman ρ of fact-level mean D1")
    w("Caveats (stats-reviewer G2, finding 10):")
    w("- k̄ is each model's mean number of correct paraphrases per fact over its whole included fact set (`p2_analysis.py`), not over the common facts.")
    w("- G(k) assumes the same k paraphrases for every fact; correct-set fact means average different paraphrase subsets (1–10), so G(k̄) overstates their reliability and the disattenuated value is under-corrected.")
    w("- ρ pools across relations while G is a within-relation quantity.")
    w("- No interval for ρ was preregistered; none is reported.")
    w("- Facts with a single correct paraphrase are included, as in the rest of the `correct` set.")
    w("")
    w("| pair | N facts | ρ | k̄ | G(k̄) | disattenuated (approx.) |")
    w("|---|---|---|---|---|---|")
    for k, v in dc["H3"].items():
        if "rho" in v:
            w(f"| {k} | {v['n_facts']} | {v['rho']:.3f} | {v['kbar'][0]:.2f}, {v['kbar'][1]:.2f} | {v['G_kbar'][0]:.3f}, {v['G_kbar'][1]:.3f} | {f3(v['disattenuated_approx'])} |")
        else:
            w(f"| {k} | MISSING: {v['missing']} | | | | |")
    w("")
    w("## 6. Sensitivities (preregistered; not gating)")
    w("The H1 / H1-alt columns below are descriptive only: per prereg section 3 a sensitivity cannot establish or rescue a claim, "
      "even where its own (non-gating) decision file computes a family-level flag.")
    w("")
    w("| set | model | rows / facts | ICC(1) D1 [CI] | diff D1 [CI] | diff D4 [CI] | MoM diff D1 / D4 | H1 | H1-alt | singular D1/D4; warnings D1/D4 |")
    w("|---|---|---|---|---|---|---|---|---|---|")
    for s in ("new226", "all", "all10", "nomanufacturer", "tcov"):
        if s not in R:
            w(f"| {s} | MISSING: not run | | | | | | | |"); continue
        for m in inc:
            mm = R[s]["models"].get(m, {}); p = D[s]["per_model"].get(m, {})
            if mm.get("status") != "ok":
                w(f"| {s} | {m} | {mm.get('status', 'MISSING')} | | | | | | |"); continue
            f1, f4 = mm["fits"]["D1"], mm["fits"]["D4"]
            ok1, ok4 = f1.get("status") == "ok", f4.get("status") == "ok"
            w(f"| {s} | {m} | {mm['n_rows']} / {mm['n_facts']} | "
              f"{(f3(f1['point']['icc1']) + ' ' + ci(f1['boot']['ci']['icc1'])) if ok1 else f1.get('status')} | "
              f"{(f3(f1['point']['diff']) + ' ' + ci(f1['boot']['ci']['diff'])) if ok1 else 'MISSING'} | "
              f"{(f3(f4['point']['diff']) + ' ' + ci(f4['boot']['ci']['diff'])) if ok4 else f4.get('status')} | "
              f"{f3(mm['mom']['D1'].get('diff'))} / {f3(mm['mom']['D4'].get('diff'))} | {p.get('H1')} | {p.get('H1_alt')} | "
              f"{f1.get('singular')}/{f4.get('singular')}; {nwarn(f1)}/{nwarn(f4)} |")
    w("")
    if "lofo" in R:
        w("Leave-one-frame-out (`lofo`, point estimates): range over the 10 dropped frames.")
        w("")
        w("| model | ICC(1) D1 min–max | ICC(1) D4 min–max | diff D1 min–max | diff D4 min–max | MoM diff D1 min–max | MoM diff D4 min–max |")
        w("|---|---|---|---|---|---|---|")
        for m in inc:
            mm = R["lofo"]["models"].get(m, {})
            if mm.get("status") != "ok":
                w(f"| {m} | {mm.get('status', 'MISSING')} | | | |"); continue
            def rng(vals):
                v = [x for x in vals if x is not None]
                return f"{min(v):.3f} – {max(v):.3f} (n={len(v)})" if v else "MISSING"
            fits = mm["fits"]
            w(f"| {m} | {rng([fits[k]['D1']['point']['icc1'] if fits[k]['D1'].get('status') == 'ok' else None for k in fits])} | "
              f"{rng([fits[k]['D4']['point']['icc1'] if fits[k]['D4'].get('status') == 'ok' else None for k in fits])} | "
              f"{rng([fits[k]['D1']['point']['diff'] if fits[k]['D1'].get('status') == 'ok' else None for k in fits])} | "
              f"{rng([fits[k]['D4']['point']['diff'] if fits[k]['D4'].get('status') == 'ok' else None for k in fits])} | "
              f"{rng([mm['mom'][k]['D1'].get('diff') for k in mm['mom']])} | "
              f"{rng([mm['mom'][k]['D4'].get('diff') for k in mm['mom']])} |")
        nsing = sum(1 for m in inc for k in R['lofo']['models'][m]['fits'] for y in ('D1', 'D4')
                    if R['lofo']['models'][m]['fits'][k][y].get('singular'))
        nw = sum(nwarn(R['lofo']['models'][m]['fits'][k][y]) for m in inc
                    for k in R['lofo']['models'][m]['fits'] for y in ('D1', 'D4'))
        w("")
        w(f"lofo fits: {nsing} singular, {nw} convergence warnings in total (of {2 * 10 * len(inc)} fits).")
        w("")
    else:
        w("Leave-one-frame-out: MISSING (not run).")
        w("")
    if "h4" in R:
        w("H4 (EXPLORATORY; frame fixed effects, point estimates): see `results/P2analysis/h4/p2_results.json` (`fixef`). "
          "The second H4 part (wording share larger in Qwen3 / Llama / OLMo than in Pythia) is MISSING: Qwen3 and both Pythia models are MISSING (insufficient data).")
    else:
        w("H4 (EXPLORATORY): MISSING (not run).")
    w("")
    w("## 7. MISSING")
    miss = [f"{m}: {rc['models'][m]['status']}" for m in ORDER if rc["models"][m]["status"] != "ok"]
    miss += [f"set {s}: not run" for s in SETS if s not in R]
    miss.append("robustness simulation (prereg section 4; non-selecting; cannot change any decision): MISSING, not run "
                "(its code was to be written and committed before it runs, and it runs only when no other heavy job runs)")
    miss.append("H4 cross-family comparison (EXPLORATORY): MISSING (Qwen3, pythia-1.4b, pythia-2.8b MISSING)")
    miss.append("INR spent and VM minutes: INR about 354 (human figure; approximate); VM minutes MISSING")
    for x in miss:
        w(f"- {x}")
    Path(out).parent.mkdir(parents=True, exist_ok=True)
    Path(out).write_text("\n".join(L) + "\n")
    print("wrote", out)


if __name__ == "__main__":
    main(sys.argv[1].split("=", 1)[1] if len(sys.argv) > 1 else str(ROOT / "reports/p2/RESULTS.md"))
